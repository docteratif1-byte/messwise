#!/usr/bin/env python3
"""Writes app/src/main/res/values{,-ur}/strings.xml from tools/strings.py and checks them against the code.

Checks: every R.string key used in Kotlin exists, English and Urdu use the same placeholders,
and calls pass as many values as the text expects.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from strings import S  # noqa: E402
try:
    from strings import P  # noqa: E402
except ImportError:
    P = {}

SRC = os.path.join(ROOT, "app/src/main/java")
RES = os.path.join(ROOT, "app/src/main/res")


def esc(s: str) -> str:
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s


def placeholders(s: str):
    return sorted(set(re.findall(r"%(\d+)\$([sd])", s)))


plural_keys = set()


def used_keys():
    keys, calls = set(), {}
    global plural_keys
    for root, _, files in os.walk(SRC):
        for f in files:
            if not f.endswith(".kt"):
                continue
            text = open(os.path.join(root, f), encoding="utf-8").read()
            keys.update(re.findall(r"R\.string\.([a-z0-9_]+)", text))
            plural_keys.update(re.findall(r"R\.plurals\.([a-z0-9_]+)", text))
            for m in re.finditer(r"(?:stringResource|getString)\(R\.string\.([a-z0-9_]+)\s*([,)])", text):
                k = m.group(1)
                if m.group(2) == ")":
                    calls.setdefault(k, set()).add(0)
                    continue
                i = m.end(); depth = 1; j = i
                while j < len(text) and depth > 0:
                    if text[j] in "([{": depth += 1
                    elif text[j] in ")]}": depth -= 1
                    j += 1
                args = text[i:j - 1]
                n, d, cur = 0, 0, ""
                for ch in args:
                    if ch in "([{": d += 1
                    if ch in ")]}": d -= 1
                    if ch == "," and d == 0:
                        n += 1; cur = ""
                    else:
                        cur += ch
                if cur.strip(): n += 1
                calls.setdefault(k, set()).add(n)
    return keys, calls


def main():
    keys, calls = used_keys()
    problems = []
    for k in sorted(keys):
        if k not in S:
            problems.append(f"missing text: {k}")
    for k, (en, ur) in S.items():
        if placeholders(en) != placeholders(ur):
            problems.append(f"placeholders differ: {k}: {placeholders(en)} vs {placeholders(ur)}")
        need = len(placeholders(en))
        for n in calls.get(k, set()):
            if n != need and not (n == 0 and need == 0):
                problems.append(f"wrong argument count for {k}: text needs {need}, code passes {n}")
    for k in sorted(plural_keys):
        if k not in P:
            problems.append(f"missing plural: {k}")
    for k, (en, ur) in P.items():
        for a in en + ur:
            if placeholders(a) != [("1", "d")]:
                problems.append(f"plural {k} must use %1$d: {a}")
    unused = sorted(set(S) - keys) + sorted(set(P) - plural_keys)
    for lang, idx, folder in (("en", 0, "values"), ("ur", 1, "values-ur")):
        os.makedirs(os.path.join(RES, folder), exist_ok=True)
        with open(os.path.join(RES, folder, "strings.xml"), "w", encoding="utf-8") as out:
            out.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_strings.py from tools/strings.py. Edit there. -->\n<resources>\n')
            for k in sorted(S):
                v = S[k][idx]
                fmt = ' formatted="false"' if "%%" in v and not placeholders(v) else ""
                tr = ' translatable="false"' if k == "app_name" and idx == 0 else ""
                out.write(f'    <string name="{k}"{tr}{fmt}>{esc(v)}</string>\n')
            for k in sorted(P):
                one, other = P[k][idx]
                out.write(f'    <plurals name="{k}">\n        <item quantity="one">{esc(one)}</item>\n        <item quantity="other">{esc(other)}</item>\n    </plurals>\n')
            out.write("</resources>\n")
    print(f"{len(S)} texts, {len(keys)} used, {len(unused)} unused")
    if unused:
        print("unused:", ", ".join(unused))
    if problems:
        print("\n".join(problems))
        sys.exit(1)


if __name__ == "__main__":
    main()
